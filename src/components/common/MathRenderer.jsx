import React, { useMemo } from "react";
import katex from "katex";
import "katex/dist/katex.min.css";

/**
 * Minifies generated HTML to prevent whitespace-pre-wrap from producing empty line boxes
 */
function minifyHtml(s) {
  if (!s) return "";
  return s.replace(/\r?\n\s*/g, " ").replace(/>\s+</g, "><").trim();
}

/**
 * Distinguishes genuine KaTeX mathematical expressions from plain financial currency or English phrases
 */
function isMathExpression(str) {
  const trimmed = str.trim();
  if (!trimmed) return false;

  // Math operators, relations, greek letters, exponents, or LaTeX commands
  if (/[\\{}^_+\-*\/=<>≤≥≠±×÷√∫∑∏]/.test(trimmed)) return true;

  // Typical currency expressions, ranges, or word intervals
  if (/\b(and|to|or|each|per|million|billion|thousand)\b/i.test(trimmed)) return false;

  // Pure numbers or simple alphanumeric labels like 140M or 25%
  if (/^[0-9.,]+[a-zA-Z%]?$/.test(trimmed)) return false;

  return true;
}

/**
 * Parses and renders mixed Markdown and KaTeX math text.
 * Supports:
 * - Block math: $$ ... $$ and \[ ... \]
 * - Inline math: $ ... $ and \( ... \)
 * - Fenced code blocks: ```lang ... ```
 * - Inline code: ` ... `
 * - Markdown tables with smart currency/numeric column formatting
 * - Interactive bar, line, and pie visualizations for data interpretation
 * - Basic markdown formatting: bold, italic, section dividers
 */
export function renderMathAndMarkdown(rawText) {
  if (!rawText || typeof rawText !== "string") return "";

  const tokens = [];
  const addToken = (html) => {
    tokens.push(html);
    return `___MATH_TOKEN_${tokens.length - 1}___`;
  };

  // 0. Pre-clean escaped dollar representations commonly generated by AI models
  let text = rawText
    .replace(/\$\\text\{\\\$\}\$/g, "$")
    .replace(/\$\\\$\$/g, "$")
    .replace(/\$\\\$/g, "$")
    .replace(/\\\$([0-9])/g, "$$$1");

  // 1. Preserve fenced code blocks
  text = text.replace(/```([a-zA-Z0-9_-]*)\n?([\s\S]*?)```/g, (match, lang, code) => {
    const escaped = code
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");
    return addToken(
      minifyHtml(
        `<pre class="bg-slate-900 text-slate-100 p-3.5 rounded-xl font-mono text-xs overflow-x-auto my-2.5 border border-slate-800 shadow-inner whitespace-pre"><code>${escaped}</code></pre>`
      )
    );
  });

  // 2. Preserve inline code
  text = text.replace(/`([^`\n\r]+)`/g, (match, code) => {
    const escaped = code
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;");
    return addToken(
      minifyHtml(
        `<code class="bg-slate-200/80 text-slate-800 font-mono text-[11px] px-1.5 py-0.5 rounded border border-slate-300/60 font-semibold">${escaped}</code>`
      )
    );
  });

  // 3. Block math: $$ ... $$
  text = text.replace(/\$\$([\s\S]+?)\$\$/g, (match, formula) => {
    try {
      const rendered = katex.renderToString(formula.trim(), {
        displayMode: true,
        throwOnError: false,
        strict: false
      });
      return addToken(
        minifyHtml(`<div class="my-3 overflow-x-auto text-center py-1 bg-slate-50/60 rounded-lg whitespace-normal">${rendered}</div>`)
      );
    } catch (e) {
      return match;
    }
  });

  // Block math: \[ ... \]
  text = text.replace(/\\\[([\s\S]+?)\\\]/g, (match, formula) => {
    try {
      const rendered = katex.renderToString(formula.trim(), {
        displayMode: true,
        throwOnError: false,
        strict: false
      });
      return addToken(
        minifyHtml(`<div class="my-3 overflow-x-auto text-center py-1 bg-slate-50/60 rounded-lg whitespace-normal">${rendered}</div>`)
      );
    } catch (e) {
      return match;
    }
  });

  // 4. Inline math: $ ... $ (strictly forbidding pipes | and ignoring plain currency)
  text = text.replace(
    /(?<!\\)\$([^\s\|\$\n\r](?:[^\|\$\n\r]*?[^\s\|\$\n\r])?)\$(?!\d|\s*(?:million|billion|k|M|B)\b)/g,
    (match, formula) => {
      if (!formula || !isMathExpression(formula)) return match;
      try {
        const rendered = katex.renderToString(formula.trim(), {
          displayMode: false,
          throwOnError: false,
          strict: false
        });
        return addToken(rendered);
      } catch (e) {
        return match;
      }
    }
  );

  // Inline math: \( ... \)
  text = text.replace(/\\\(([\s\S]+?)\\\)/g, (match, formula) => {
    try {
      const rendered = katex.renderToString(formula.trim(), {
        displayMode: false,
        throwOnError: false,
        strict: false
      });
      return addToken(rendered);
    } catch (e) {
      return match;
    }
  });

  // 5. Competitive programming section dividers
  text = text.replace(
    /-----+(Input|Output|Example|Examples|Note|Notes|Constraints|Specification)-----+(\n|$)/gi,
    (match, title) => {
      return addToken(
        minifyHtml(
          `<div class="font-bold text-xs uppercase tracking-wider text-indigo-700 bg-indigo-50/90 px-2.5 py-1 rounded-md border border-indigo-200/70 my-3.5 inline-flex items-center gap-1.5 shadow-2xs whitespace-normal">${title}</div>`
        )
      );
    }
  );

  // 5b. Pie Chart Visualizer
  const pieLineRegex = /^[*-]\s*([^:\n\r]+?)\s*:\s*(\d+(?:\.\d+)?)\s*(degrees?|deg|%|percent)/gim;
  const pieMatches = [];
  let pMatch;
  while ((pMatch = pieLineRegex.exec(text)) !== null) {
    const label = pMatch[1].trim();
    const val = parseFloat(pMatch[2]);
    const unit = pMatch[3].toLowerCase();
    const degrees = unit.startsWith("deg") ? val : (val / 100) * 360;
    pieMatches.push({ label, degrees, rawVal: pMatch[2] + (unit.startsWith("%") ? "%" : "°") });
  }

  if (pieMatches.length >= 3 && /pie\s*(chart|graph|distribution|allocation)/i.test(rawText)) {
    const totalDeg = pieMatches.reduce((s, it) => s + it.degrees, 0) || 360;
    const colors = ["#2563EB", "#0F172A", "#64748B", "#38BDF8", "#F59E0B", "#10B981", "#8B5CF6"];
    const cx = 90, cy = 90, r = 75, innerR = 30;
    let currentAngle = -90;

    const paths = pieMatches.map((it, idx) => {
      const sliceAngle = (it.degrees / totalDeg) * 360;
      const startAngle = currentAngle;
      const endAngle = currentAngle + sliceAngle;
      currentAngle = endAngle;

      const rad = Math.PI / 180;
      const x1 = cx + r * Math.cos(startAngle * rad);
      const y1 = cy + r * Math.sin(startAngle * rad);
      const x2 = cx + r * Math.cos(endAngle * rad);
      const y2 = cy + r * Math.sin(endAngle * rad);

      const xi1 = cx + innerR * Math.cos(startAngle * rad);
      const yi1 = cy + innerR * Math.sin(startAngle * rad);
      const xi2 = cx + innerR * Math.cos(endAngle * rad);
      const yi2 = cy + innerR * Math.sin(endAngle * rad);

      const largeArc = sliceAngle > 180 ? 1 : 0;
      const pathData = `M ${xi1} ${yi1} L ${x1} ${y1} A ${r} ${r} 0 ${largeArc} 1 ${x2} ${y2} L ${xi2} ${yi2} A ${innerR} ${innerR} 0 ${largeArc} 0 ${xi1} ${yi1} Z`;
      const color = colors[idx % colors.length];

      return `<path d="${pathData}" fill="${color}" stroke="#ffffff" stroke-width="2" />`;
    }).join("");

    const legend = pieMatches.map((it, idx) => {
      const color = colors[idx % colors.length];
      const pct = Math.round((it.degrees / totalDeg) * 100);
      return minifyHtml(`
        <div class="flex items-center justify-between gap-3 text-xs py-1 border-b border-slate-100 last:border-0">
          <div class="flex items-center gap-2 min-w-0">
            <span class="w-2.5 h-2.5 rounded-full shrink-0" style="background-color: ${color}"></span>
            <span class="font-medium text-slate-700 truncate">${it.label}</span>
          </div>
          <div class="font-mono text-slate-900 shrink-0 font-bold">${it.rawVal} <span class="text-slate-400 font-normal text-[10px]">(${pct}%)</span></div>
        </div>
      `);
    }).join("");

    const pieHtml = minifyHtml(`
      <div class="my-4 p-4 rounded-xl border border-slate-200/90 bg-white shadow-2xs whitespace-normal max-w-xl font-sans leading-normal">
        <div class="text-[11px] uppercase font-bold text-slate-500 tracking-wider mb-3 flex items-center gap-1.5">
          <span class="w-2 h-2 rounded-full bg-blue-600"></span> Visual Pie Chart Distribution
        </div>
        <div class="flex flex-col sm:flex-row items-center justify-center gap-6">
          <svg width="180" height="180" viewBox="0 0 180 180" class="shrink-0 drop-shadow-xs">
            ${paths}
          </svg>
          <div class="w-full sm:max-w-xs space-y-0.5">
            ${legend}
          </div>
        </div>
      </div>
    `);
    text = addToken(pieHtml) + "\n" + text;
  }

  // 5c. Markdown Tables & Visual Graphs (Bar Graphs, Line Graphs, Data Tables)
  const tableRegex = /((?:\|[^\n\r]+\|(?:\r?\n|$))+)/g;
  text = text.replace(tableRegex, (match) => {
    const lines = match.trim().split(/\r?\n/).map(l => l.trim()).filter(Boolean);
    if (lines.length < 2) return match;
    const sepLine = lines[1];
    if (!sepLine.includes("---")) return match;

    const parseRow = (line) => line.split("|").slice(1, -1).map(c => c.trim());
    const rawHeaders = parseRow(lines[0]);
    const rawAlignRules = parseRow(sepLine).map(c => {
      if (c.startsWith(":") && c.endsWith(":")) return "text-center";
      if (c.endsWith(":")) return "text-right";
      return "text-left";
    });

    const rawRows = lines.slice(2).map(parseRow);

    // Prune columns where the header is empty AND all row cells are empty
    const validColIndices = [];
    for (let c = 0; c < rawHeaders.length; c++) {
      const hasHeader = rawHeaders[c] && rawHeaders[c].trim().length > 0;
      const hasData = rawRows.some(r => r[c] && r[c].trim().length > 0);
      if (hasHeader || hasData) {
        validColIndices.push(c);
      }
    }

    if (validColIndices.length === 0) return match;

    const headers = validColIndices.map(c => rawHeaders[c] || "");
    const rows = rawRows.map(r => validColIndices.map(c => r[c] || ""));
    const alignRules = validColIndices.map(c => rawAlignRules[c] || "text-left");

    // Detect if column values are predominantly numeric / currency / percentage
    const colIsNumeric = headers.map((_, i) => {
      let numCount = 0;
      let dataCount = 0;
      for (const row of rows) {
        const val = row[i];
        if (val && val.trim()) {
          dataCount++;
          const cleaned = val.replace(/[$€£₹¥%,\s]/g, "").replace(/(million|billion|thousand|[kKmMbB])\s*$/i, "").trim();
          if (!isNaN(parseFloat(cleaned)) && isFinite(cleaned)) {
            numCount++;
          }
        }
      }
      return dataCount > 0 && (numCount / dataCount) >= 0.5;
    });

    let graphVisualHtml = "";
    const isBarGraph = /bar\s*(graph|chart)/i.test(rawText);
    const isLineGraph = /line\s*(graph|chart)/i.test(rawText);

    if (isBarGraph && headers.length >= 2 && rows.length >= 2) {
      let numColIdx = -1;
      for (let c = 1; c < headers.length; c++) {
        if (colIsNumeric[c]) {
          numColIdx = c;
          break;
        }
      }

      if (numColIdx !== -1) {
        const barData = rows.map(r => {
          const raw = r[numColIdx] || "";
          const cleaned = raw.replace(/[$€£₹¥%,\s]/g, "").replace(/(million|billion|thousand|[kKmMbB])\s*$/i, "").trim();
          const num = parseFloat(cleaned) || 0;
          return { label: r[0] || "Item", value: num, raw };
        });

        const maxVal = Math.max(...barData.map(b => b.value)) || 1;
        const colHeader = headers[numColIdx] || "Value";

        const barsHtml = barData.map((b) => {
          const pct = Math.min(100, Math.max(2, Math.round((b.value / maxVal) * 100)));
          return minifyHtml(`
            <div class="py-1">
              <div class="flex items-center justify-between text-xs mb-1.5">
                <span class="font-semibold text-slate-800 truncate">${b.label}</span>
                <div class="flex items-center gap-2 shrink-0">
                  <span class="font-mono font-bold text-slate-900">${b.raw}</span>
                  <span class="text-[10px] font-mono text-slate-500 bg-slate-100 px-1.5 py-0.5 rounded">${pct}%</span>
                </div>
              </div>
              <div class="h-4 bg-slate-100 rounded-md overflow-hidden relative border border-slate-200/60">
                <div class="h-full bg-blue-600 rounded-md transition-all duration-500" style="width: ${pct}%"></div>
              </div>
            </div>
          `);
        }).join("");

        const scaleMarks = [0, 0.25, 0.5, 0.75, 1.0].map(fraction => {
          const val = Math.round(maxVal * fraction);
          const label = val >= 1000000 ? `${(val / 1000000).toFixed(1)}M` : (val >= 1000 ? `${(val / 1000).toFixed(0)}k` : `${val}`);
          return `<span>${label}</span>`;
        }).join("");

        graphVisualHtml = minifyHtml(`
          <div class="my-5 p-5 rounded-xl border border-slate-200/90 bg-white shadow-2xs whitespace-normal max-w-2xl font-sans leading-normal">
            <div class="flex items-center justify-between pb-3 mb-3 border-b border-slate-100 text-xs">
              <div class="flex items-center gap-2 font-bold text-slate-800 uppercase tracking-wide text-[11px]">
                <span class="w-2.5 h-2.5 rounded-full bg-blue-600"></span>
                <span>Bar Graph: ${colHeader}</span>
              </div>
              <span class="text-[11px] font-mono text-slate-500">Max: ${maxVal.toLocaleString()}</span>
            </div>
            <div class="space-y-2">
              ${barsHtml}
            </div>
            <div class="mt-4 pt-2 border-t border-slate-100 flex items-center justify-between text-[10px] font-mono text-slate-400">
              ${scaleMarks}
            </div>
          </div>
        `);
      }
    } else if (isLineGraph && headers.length >= 2 && rows.length >= 2) {
      let numColIdx = -1;
      for (let c = 1; c < headers.length; c++) {
        if (colIsNumeric[c]) {
          numColIdx = c;
          break;
        }
      }
      if (numColIdx === -1) numColIdx = 1;

      const pts = rows.map((r, i) => {
        const raw = r[numColIdx] || "";
        const cleaned = raw.replace(/[$€£₹¥%,\s]/g, "").replace(/(million|billion|thousand|[kKmMbB])\s*$/i, "").trim();
        const num = parseFloat(cleaned) || 0;
        return { label: r[0], value: num, raw, idx: i };
      });
      const maxVal = Math.max(...pts.map(p => p.value)) || 1;
      const minVal = Math.min(...pts.map(p => p.value)) || 0;
      const range = maxVal - minVal || 1;

      const svgW = 360, svgH = 130, padX = 40, padY = 22;
      const stepX = (svgW - padX * 2) / (pts.length - 1 || 1);

      const pointsCoords = pts.map((p, i) => {
        const x = padX + i * stepX;
        const y = svgH - padY - ((p.value - minVal) / range) * (svgH - padY * 2);
        return { ...p, x, y };
      });

      const polyline = pointsCoords.map(p => `${p.x},${p.y}`).join(" ");
      const dots = pointsCoords.map(p => `
        <circle cx="${p.x}" cy="${p.y}" r="4" fill="#2563EB" stroke="#ffffff" stroke-width="2" />
        <text x="${p.x}" y="${p.y - 7}" text-anchor="middle" font-size="9" fill="#0F172A" font-weight="bold">${p.raw}</text>
        <text x="${p.x}" y="${svgH - 4}" text-anchor="middle" font-size="8" fill="#64748B">${(p.label || "").substring(0, 3)}</text>
      `).join("");

      graphVisualHtml = minifyHtml(`
        <div class="my-4 p-4 rounded-xl border border-slate-200/90 bg-white shadow-2xs whitespace-normal max-w-xl font-sans leading-normal">
          <div class="text-[11px] uppercase font-bold text-slate-500 tracking-wider mb-2 flex items-center justify-between">
            <span class="flex items-center gap-1.5"><span class="w-2 h-2 rounded-full bg-blue-600"></span> Visual Line Graph Trend (${headers[numColIdx]})</span>
          </div>
          <svg width="100%" height="130" viewBox="0 0 ${svgW} ${svgH}" class="overflow-visible">
            <line x1="${padX}" y1="${padY}" x2="${padX}" y2="${svgH - padY}" stroke="#E2E8F0" stroke-width="1" />
            <line x1="${padX}" y1="${svgH - padY}" x2="${svgW - padX / 2}" y2="${svgH - padY}" stroke="#E2E8F0" stroke-width="1" />
            <polyline fill="none" stroke="#2563EB" stroke-width="2.5" stroke-linecap="round" stroke-linejoin="round" points="${polyline}" />
            ${dots}
          </svg>
        </div>
      `);
    }

    const thead = '<thead class="bg-slate-50 text-slate-700 font-bold border-b border-slate-200"><tr>' +
      headers.map((h, i) => {
        let align = alignRules[i] || (colIsNumeric[i] ? "text-right" : "text-left");
        if (alignRules[i] === "text-center") align = "text-center";
        return `<th class="px-4 py-2.5 ${align}">${h}</th>`;
      }).join("") +
      '</tr></thead>';

    const tbody = '<tbody class="divide-y divide-slate-100 text-slate-800">' +
      rows.map(row => '<tr class="hover:bg-slate-50/50">' +
        row.map((c, i) => {
          const trimmed = c.trim();
          let align = alignRules[i] || (colIsNumeric[i] ? "text-right" : "text-left");
          if (alignRules[i] === "text-center") align = "text-center";
          
          if (!trimmed) {
            return `<td class="px-4 py-2.5 text-center text-slate-300 font-normal select-none">&mdash;</td>`;
          }

          const cellClass = colIsNumeric[i]
            ? `px-4 py-2.5 ${align} font-mono tabular-nums font-semibold text-slate-900`
            : `px-4 py-2.5 ${align} font-medium text-slate-800`;
          return `<td class="${cellClass}">${trimmed}</td>`;
        }).join("") +
      '</tr>').join("") +
      '</tbody>';

    const tableHtml = minifyHtml(`
      <div class="my-3 overflow-x-auto rounded-xl border border-slate-200 bg-white shadow-2xs whitespace-normal max-w-full font-sans leading-normal">
        <table class="w-full text-left text-xs border-collapse">
          ${thead}
          ${tbody}
        </table>
      </div>
    `);

    return addToken(graphVisualHtml + tableHtml);
  });

  // 6. Markdown Bold & Italic
  text = text.replace(/\*\*([^*]+)\*\*/g, "<strong class=\"font-bold text-slate-900\">$1</strong>");
  text = text.replace(/(?<!\*)\*([^*]+)\*(?!\*)/g, "<em class=\"italic\">$1</em>");

  // 7. Clean up escaped dollar signs
  text = text.replace(/\\(\$)/g, "$1");

  // 8. Restore all saved tokens recursively (Math & Code & Visuals)
  let maxPasses = 10;
  while (text.includes("___MATH_TOKEN_") && maxPasses-- > 0) {
    text = text.replace(/___MATH_TOKEN_(\d+)___/g, (_, idx) => {
      const token = tokens[parseInt(idx, 10)];
      return token !== undefined ? token : "";
    });
  }

  return text;
}

/**
 * React Component for rendering text with KaTeX formulas and Markdown.
 */
export function MathRenderer({ content, className = "", inline = false }) {
  const html = useMemo(() => {
    return renderMathAndMarkdown(content);
  }, [content]);

  if (!content) return null;

  if (inline) {
    return (
      <span
        className={`math-rendered-inline inline align-baseline ${className}`}
        dangerouslySetInnerHTML={{ __html: html }}
      />
    );
  }

  return (
    <div
      className={`math-rendered-block whitespace-pre-wrap leading-relaxed ${className}`}
      dangerouslySetInnerHTML={{ __html: html }}
    />
  );
}

export default MathRenderer;
